  applyExplodeFactor(factor) {
    this.explodeFactor = factor;

    // 1. Bodywork Aero Shell: Lifts high and tilts slightly backward to reveal entire chassis & powertrain
    if (this.parts.body) {
      this.parts.body.position.y = factor * 1.35;
      this.parts.body.position.z = -factor * 0.15;
      this.parts.body.rotation.x = factor * 0.08;
    }

    // 2. Glass Elements & Headlights: Rigidly anchored to the lifting bodywork shell
    ['glass', 'lights', 'lightsNoOpacity', 'redlight'].forEach((partKey) => {
      const part = this.parts[partKey];
      if (part && this.parts.body) {
        part.position.copy(this.parts.body.position);
        part.rotation.copy(this.parts.body.rotation);
      }
    });

    // 3. Engine Block: Lifts out of the monocoque bay
    if (this.parts.engine) {
      this.parts.engine.position.y = factor * 0.35;
      this.parts.engine.position.z = -factor * 0.05;
    }

    // 4. Mechanical Subsystems:
    const mech = this.parts.mechanical;
    if (mech) {
      // Velocity stacks & Holley carburetors: lift higher above engine block
      if (mech.engineDetails) {
        mech.engineDetails.position.y = factor * 0.75;
        mech.engineDetails.position.z = -factor * 0.05;
      }
      // Finned Valve Covers: separate outward laterally
      if (mech.valveCovers) {
        if (mech.valveCovers.left) {
          mech.valveCovers.left.position.x = -0.22 - factor * 0.28;
          mech.valveCovers.left.position.y = 0.36 + factor * 0.18;
        }
        if (mech.valveCovers.right) {
          mech.valveCovers.right.position.x = 0.22 + factor * 0.28;
          mech.valveCovers.right.position.y = 0.36 + factor * 0.18;
        }
      }
      // Engine front accessories (alternator, starter, oil filter)
      if (mech.engineAccessories) {
        mech.engineAccessories.position.y = factor * 0.25;
        mech.engineAccessories.position.z = factor * 0.15;
      }
      // "Bundle of Snakes" crossover exhaust: separates from heads & rises
      if (mech.exhaust) {
        mech.exhaust.position.y = factor * 0.55;
        mech.exhaust.position.z = -factor * 0.25;
      }
      // Kar Kraft T-44 transaxle: decouples rearward from flywheel
      if (mech.transaxleDetails) {
        mech.transaxleDetails.position.z = -factor * 0.55;
        mech.transaxleDetails.position.y = factor * 0.14;
      }
      // Phil Remington Quick-Change Brakes: expand outward laterally with wheels
      if (mech.brakeSystem && mech.brakeSystem.corners) {
        const brakeDistX = factor * 0.65;
        const brakeDistZ = factor * 0.15;
        const bc = mech.brakeSystem.corners;
        if (bc.FL) { bc.FL.position.x = -0.76 - brakeDistX; bc.FL.position.z = 1.25 + brakeDistZ; }
        if (bc.FR) { bc.FR.position.x = 0.76 + brakeDistX;  bc.FR.position.z = 1.25 + brakeDistZ; }
        if (bc.RL) { bc.RL.position.x = -0.76 - brakeDistX; bc.RL.position.z = -1.10 - brakeDistZ; }
        if (bc.RR) { bc.RR.position.x = 0.76 + brakeDistX;  bc.RR.position.z = -1.10 - brakeDistZ; }
      }
      // Front cooling radiator & swirl tank
      if (mech.frontCooling) {
        mech.frontCooling.position.y = factor * 0.20;
        mech.frontCooling.position.z = factor * 0.35;
      }
      // Suspension coilovers & A-arms: expand outward laterally
      const suspDistX = factor * 0.35;
      const suspDistZ = factor * 0.15;
      const s = mech.suspensionDetails;
      if (s.FL) { s.FL.position.x = -0.68 - suspDistX; s.FL.position.z = 1.25 + suspDistZ; }
      if (s.FR) { s.FR.position.x = 0.68 + suspDistX;  s.FR.position.z = 1.25 + suspDistZ; }
      if (s.RL) { s.RL.position.x = -0.66 - suspDistX; s.RL.position.z = -1.08 - suspDistZ; }
      if (s.RR) { s.RR.position.x = 0.66 + suspDistX;  s.RR.position.z = -1.08 - suspDistZ; }

      // Anti-roll sway bars: drop down slightly
      if (mech.swayBars) {
        mech.swayBars.position.y = -factor * 0.12;
      }
      // Fuel bladders: separate laterally in door sills
      if (mech.fuelSystem) {
        if (mech.fuelSystem.leftBladder) mech.fuelSystem.leftBladder.position.x = -0.66 - factor * 0.25;
        if (mech.fuelSystem.rightBladder) mech.fuelSystem.rightBladder.position.x = 0.66 + factor * 0.25;
      }
      // Cockpit controls: rise slightly
      if (mech.cockpitDetails) {
        mech.cockpitDetails.position.y = factor * 0.16;
      }
      // Chassis aerodynamic details (ducktail spoiler & roll hoop)
      if (mech.chassisDetails) {
        mech.chassisDetails.position.y = factor * 0.18;
      }
    }

    // 5. Interior: Anchors cleanly to the monocoque chassis
    if (this.parts.interior) {
      this.parts.interior.position.y = -factor * 0.08;
    }

    // 6. Complete Wheels (Halibrand Magnesium Disks + Goodyear Rubber Slicks explode together)
    const w = this.parts.wheels;
    const d = this.parts.disks;
    const wheelDistX = factor * 0.85;
    const wheelDistZ = factor * 0.15;
    if (w.FL) { w.FL.position.x = -wheelDistX; w.FL.position.z = wheelDistZ; }
    if (w.FR) { w.FR.position.x = wheelDistX;  w.FR.position.z = wheelDistZ; }
    if (w.RL) { w.RL.position.x = -wheelDistX; w.RL.position.z = -wheelDistZ; }
    if (w.RR) { w.RR.position.x = wheelDistX;  w.RR.position.z = -wheelDistZ; }

    if (d.FL) { d.FL.position.x = -wheelDistX; d.FL.position.z = wheelDistZ; }
    if (d.FR) { d.FR.position.x = wheelDistX;  d.FR.position.z = wheelDistZ; }
    if (d.RL) { d.RL.position.x = -wheelDistX; d.RL.position.z = -wheelDistZ; }
    if (d.RR) { d.RR.position.x = wheelDistX;  d.RR.position.z = -wheelDistZ; }

    // Update slider UI
    const pct = Math.round(factor * 100);
    if (this.slider && this.slider.value != pct) {
      this.slider.value = pct;
    }
    if (this.sliderFill) {
      this.sliderFill.style.width = `${pct}%`;
    }
    if (this.sliderDisplay) {
      this.sliderDisplay.textContent = `${pct}%`;
    }
  }

