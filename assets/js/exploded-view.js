  setSystem(sysName) {
    if (!SYSTEM_CAMERAS[sysName]) sysName = 'all';
    this.activeSystem = sysName;

    // Update active system navigation buttons
    document.querySelectorAll('.exploded-system-btn').forEach((btn) => {
      btn.classList.toggle('active', btn.dataset.system === sysName);
    });

    // Update active 3D hotspot pins
    document.querySelectorAll('.hotspot-pin').forEach((pin) => {
      pin.classList.toggle('active', pin.dataset.target === sysName);
    });

    // Maintain authentic solid bodywork; only apply X-Ray if user toggles the X-Ray mode
    if (this.parts.body) {
      this.parts.body.material = this.isXRay ? this.bodyXRayMaterial : this.bodySolidMaterial;
    }

    const targetCfg = SYSTEM_CAMERAS[sysName];
    if (targetCfg) {
      this.startCamPos.copy(this.camera.position);
      this.endCamPos.copy(targetCfg.cam);

      this.startLookAt.copy(this.controls.target);
      this.endLookAt.copy(targetCfg.target);

      this.transitionStart = performance.now();
      this.transitionDuration = 950;
      this.isTransitioning = true;
      this.controls.enabled = false;

      this.targetExplodeFactor = targetCfg.explode;
      this.playPneumaticSound();
    }

    this.updateTelemetryCard(sysName);
  }

