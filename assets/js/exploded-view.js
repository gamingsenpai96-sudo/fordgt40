  setupEnvironmentMap() {
    try {
      const pmrem = new THREE.PMREMGenerator(this.renderer);
      pmrem.compileEquirectangularShader();

      const envScene = new THREE.Scene();
      envScene.background = new THREE.Color(0x151a24);

      // Overcast sky hemisphere
      const skyGeo = new THREE.SphereGeometry(60, 24, 16);
      const skyMat = new THREE.MeshBasicMaterial({
        color: 0x425062,
        side: THREE.BackSide
      });
      envScene.add(new THREE.Mesh(skyGeo, skyMat));

      // Ground plane in env
      const groundMat = new THREE.MeshBasicMaterial({ color: 0x16181e });
      const ground = new THREE.Mesh(new THREE.PlaneGeometry(100, 100), groundMat);
      ground.rotation.x = -Math.PI / 2;
      ground.position.y = -2;
      envScene.add(ground);

      // Soft natural daylight warmth in horizon
      const sunWarm = new THREE.Mesh(
        new THREE.SphereGeometry(8, 16, 16),
        new THREE.MeshBasicMaterial({ color: 0xfff0dd })
      );
      sunWarm.position.set(30, 25, 20);
      envScene.add(sunWarm);

      this.scene.environment = pmrem.fromScene(envScene).texture;
      pmrem.dispose();
    } catch (e) {
      console.warn('Environment map generation fallback:', e);
    }
  }

